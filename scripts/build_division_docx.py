def member_block(index: str, title: str, positioning: str, focus: list,
                 reuse: list, deliverables: list, metrics: list, boundary: list,
                 level: int = 2) -> str:
    out = [heading('{0}  {1}'.format(index, title), level)]
    out.append(para('**研究定位**　{0}'.format(positioning)))
    out.append(para('**重点研究内容**'))
    for item in focus:
        out.append(bullet(item))
    if reuse:
        out.append(para('**可复用的既有资产**'))
        for item in reuse:
            out.append(bullet(item))
    out.append(para('**独立交付物**'))
    out.append(table(['交付物', '最低内容要求'], deliverables,
                     widths=[2400, 6600]))
    out.append(para('**量化指标（内部目标值，非实测结果）**'))
    out.append(table(['指标', '口径说明'], metrics, widths=[2600, 6400]))
    if boundary:
        out.append(para('**职责边界**'))
        for item in boundary:
            out.append(bullet(item))
    return ''.join(out)


